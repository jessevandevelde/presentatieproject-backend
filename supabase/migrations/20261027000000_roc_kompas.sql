BEGIN;

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = timezone('utc', now());
  RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS public.superadmins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL CHECK (char_length(name) <= 100),
  email varchar(100) NOT NULL UNIQUE CHECK (char_length(email) <= 100),
  password_hash varchar(255) NOT NULL CHECK (char_length(password_hash) <= 255),
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.statements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text text NOT NULL,
  created_by bigint NOT NULL REFERENCES public.superadmins(id),
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.parties (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL CHECK (char_length(name) <= 100),
  description text,
  image_url varchar(255) CHECK (char_length(image_url) <= 255),
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.party_answers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party_id bigint NOT NULL REFERENCES public.parties(id),
  statement_id bigint NOT NULL REFERENCES public.statements(id),
  answer text NOT NULL CHECK (answer IN ('eens', 'neutraal', 'oneens')),
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.visualization_points (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_key uuid NOT NULL UNIQUE,
  x double precision NOT NULL CHECK (x BETWEEN -100 AND 100),
  y double precision NOT NULL CHECK (y BETWEEN -100 AND 100)
);

CREATE INDEX IF NOT EXISTS idx_statements_created_by ON public.statements(created_by);
CREATE INDEX IF NOT EXISTS idx_party_answers_party_id ON public.party_answers(party_id);
CREATE INDEX IF NOT EXISTS idx_party_answers_statement_id ON public.party_answers(statement_id);

DROP TRIGGER IF EXISTS superadmins_updated_at ON public.superadmins;
CREATE TRIGGER superadmins_updated_at BEFORE UPDATE ON public.superadmins
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS statements_updated_at ON public.statements;
CREATE TRIGGER statements_updated_at BEFORE UPDATE ON public.statements
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS parties_updated_at ON public.parties;
CREATE TRIGGER parties_updated_at BEFORE UPDATE ON public.parties
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS party_answers_updated_at ON public.party_answers;
CREATE TRIGGER party_answers_updated_at BEFORE UPDATE ON public.party_answers
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.superadmins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.statements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.parties ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.party_answers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.visualization_points ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.superadmins, public.statements, public.parties, public.party_answers, public.visualization_points FROM anon, authenticated;
GRANT USAGE ON SCHEMA public TO service_role;
GRANT ALL ON public.superadmins, public.statements, public.parties, public.party_answers, public.visualization_points TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

NOTIFY pgrst, 'reload schema';

COMMIT;
